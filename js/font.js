// Polskie litery: zwykła litera plus piksele [wiersz, kolumna] nad nią lub pod nią.
const ACUTE = [[-3, 3], [-2, 2]];
const FONT_ACCENTS = {
  Ą: { base: 'A', marks: [[7, 4], [8, 3]] },
  Ć: { base: 'C', marks: ACUTE },
  Ę: { base: 'E', marks: [[7, 3], [8, 4]] },
  Ń: { base: 'N', marks: ACUTE },
  Ó: { base: 'O', marks: ACUTE },
  Ś: { base: 'S', marks: ACUTE },
  Ź: { base: 'Z', marks: ACUTE },
  Ż: { base: 'Z', marks: [[-2, 2]] },
};

const GLYPH_W = { plain: 5, bold: 6, outline: 7 };

function textWidth(str, u, style = 'plain') {
  const gw = GLYPH_W[style];
  return (str.length * (gw + 1) - 1) * u;
}

function glyphRects(c, str, x, y, u, style, grow) {
  const adv = (GLYPH_W[style] + 1) * u;
  const bold = style === 'bold';
  const pad = style === 'outline' ? u : 0;
  c.beginPath();
  for (let i = 0; i < str.length; i++) {
    const accent = FONT_ACCENTS[str[i]];
    const rows = FONT[accent ? accent.base : str[i]];
    if (!rows) continue;
    const gx = x + i * adv + pad;
    const pixel = (r, k) => {
      const px = gx + k * u - grow;
      const py = y + pad + r * u - grow;
      c.rect(px, py, (bold ? 2 * u : u) + 2 * grow + 0.3, u + 2 * grow + 0.3);
    };
    for (let r = 0; r < 7; r++) {
      for (let k = 0; k < 5; k++) {
        if (rows[r] & (0x10 >> k)) pixel(r, k);
      }
    }
    if (accent) accent.marks.forEach(([r, k]) => pixel(r, k));
  }
}

// opts: { u, style, color, inner, align, shadow }
function drawText(c, rawStr, x, y, opts = {}) {
  const str = String(rawStr).toUpperCase();
  const u = opts.u || 3;
  const style = opts.style || 'plain';
  const w = textWidth(str, u, style);
  if (opts.align === 'center') x -= w / 2;
  if (opts.align === 'right') x -= w;
  if (opts.shadow) {
    c.fillStyle = opts.shadow;
    glyphRects(c, str, x + u * 0.7, y + u * 0.7, u, style, style === 'outline' ? u : 0);
    c.fill();
  }
  c.fillStyle = opts.color || '#fff';
  glyphRects(c, str, x, y, u, style, style === 'outline' ? u : 0);
  c.fill();
  if (style === 'outline') {
    c.fillStyle = opts.inner || '#1b2550';
    glyphRects(c, str, x, y, u, style, 0);
    c.fill();
  }
  return w;
}
